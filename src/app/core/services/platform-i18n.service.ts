  constructor() {
    this.buildRuntimeIndex();
  }

  t(key: string): string {
    const lang = this.platformLanguage.language();
    const current = this.translations[lang]?.[key];
    if (current) return current;
    return this.translations.es[key] ?? key;
  }

  translateRuntimeText(input: string): string {
    const trimmed = input.trim();
    if (!trimmed) return input;
    if (!/[A-Za-zÀ-ÿ]/.test(trimmed)) return input;
    if (this.shouldSkipRuntimeText(trimmed)) return input;

    const key = this.runtimePhraseToKey.get(this.normalizeText(trimmed));
    if (!key) {
      const fallback = this.translateByWordFallback(trimmed);
      if (!fallback || fallback === trimmed) return input;
      return this.replacePreservingWhitespace(input, fallback);
    }

    const translated = this.t(key);
    if (translated === trimmed) return input;

    return this.replacePreservingWhitespace(input, translated);
  }

  private translateByWordFallback(text: string): string {
    const lang = this.platformLanguage.language();
    if (lang === 'es') return text;

    const dict = this.fallbackWordMap[lang];
    const parts = text.split(/(\s+|[.,;:!?()\[\]{}"'¿¡\/\-]+)/);
    let changed = false;

    const translated = parts.map((part) => {
      if (!part || /^\s+$/.test(part)) return part;
      if (!/[A-Za-zÀ-ÿ]/.test(part)) return part;

      const normalized = this.normalizeText(part);
      const value = dict[normalized];
      if (!value) return part;

      changed = true;
      return this.matchCase(part, value);
    }).join('');

    return changed ? translated : text;
  }

  private shouldSkipRuntimeText(text: string): boolean {
    if (text.includes('@if') || text.includes('@for') || text.includes('{{') || text.includes('}}')) return true;
    if (/^[\[\](){}<>#*+=|]+$/.test(text)) return true;
    if (/^[-_\s]+$/.test(text)) return true;
    return false;
  }

  private buildRuntimeIndex(): void {
    const languages: PlatformLanguage[] = ['es', 'en', 'pt'];
    for (const lang of languages) {
      const dict = this.translations[lang];
      for (const key of Object.keys(dict)) {
        const value = dict[key];
        const normalized = this.normalizeText(value);
        if (!normalized) continue;
        if (!this.runtimePhraseToKey.has(normalized)) {
          this.runtimePhraseToKey.set(normalized, key);
        }
      }
    }
  }

  private replacePreservingWhitespace(original: string, translatedTrimmed: string): string {
    const leading = original.match(/^\s*/)?.[0] ?? '';
    const trailing = original.match(/\s*$/)?.[0] ?? '';
    return `${leading}${translatedTrimmed}${trailing}`;
  }

  private normalizeText(text: string): string {
    return text
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .trim();
  }

  private matchCase(source: string, translated: string): string {
    if (source.toUpperCase() === source) return translated.toUpperCase();
    if (source[0] && source[0] === source[0].toUpperCase()) {
      return translated.charAt(0).toUpperCase() + translated.slice(1);
    }
    return translated;
  }

